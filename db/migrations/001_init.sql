-- Interview Admin: початкова схема (заміна n8n Data Tables).
-- Назви полів збігаються з колишніми Data Tables, щоб логіка workflow у n8n лишилась тією самою.

-- Довідник воронок KeyCRM (раніше: n8n «Конфіг» → PIPELINES)
CREATE TABLE interview_pipelines (
  id          integer PRIMARY KEY,                 -- ID воронки в KeyCRM
  name        text    NOT NULL CHECK (btrim(name) <> ''),
  position    integer NOT NULL DEFAULT 0,          -- порядок у списках
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Співробітники, яких можна призначити відповідальними (раніше: Interview Responsibles)
CREATE TABLE interview_responsibles (
  employee_id integer PRIMARY KEY,                 -- ID співробітника в KeyCRM
  name        text    NOT NULL CHECK (btrim(name) <> ''),
  discord_id  text    NOT NULL DEFAULT '',         -- для тегу <@discord_id> у щоденному повідомленні
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Вікна групових співбесід (раніше: Interview Sessions)
CREATE TABLE interview_sessions (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id       text    NOT NULL UNIQUE DEFAULT gen_random_uuid()::text,  -- публічний ID (у посиланнях адмінпанелі)
  session_name     text    NOT NULL DEFAULT '',
  start_date       timestamptz NOT NULL,
  max_participants integer NOT NULL CHECK (max_participants > 0),
  status           text    NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Full', 'Closed')),
  pipeline_id      integer,                         -- воронка KeyCRM; NULL — стара сесія без воронки
  pipeline_name    text    NOT NULL DEFAULT '',     -- workflow бронювання шукає сесії за цією назвою
  responsible_ids  integer[] NOT NULL DEFAULT '{}', -- employee_id з interview_responsibles
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX interview_sessions_booking_idx ON interview_sessions (status, pipeline_name, start_date);
CREATE INDEX interview_sessions_start_idx ON interview_sessions (start_date);

-- Записи кандидатів на співбесіди (раніше: Interview Participants)
CREATE TABLE interview_participants (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keycrm_id           text NOT NULL,               -- ID картки KeyCRM
  name                text NOT NULL DEFAULT '',
  phone               text NOT NULL DEFAULT '',
  session_id          text NOT NULL REFERENCES interview_sessions (session_id) ON UPDATE CASCADE,
  registration_status text NOT NULL DEFAULT 'Reserved' CHECK (registration_status IN ('Reserved', 'Confirmed', 'Cancelled')),
  keycrm_sync         text NOT NULL DEFAULT 'Pending' CHECK (keycrm_sync IN ('Pending', 'Synced', 'Failed')),
  sync_error          text NOT NULL DEFAULT '',
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX interview_participants_session_idx ON interview_participants (session_id, registration_status);
CREATE INDEX interview_participants_keycrm_idx ON interview_participants (keycrm_id);

-- updated_at оновлюється автоматично при будь-якій зміні рядка
CREATE FUNCTION interview_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

CREATE TRIGGER interview_pipelines_touch    BEFORE UPDATE ON interview_pipelines    FOR EACH ROW EXECUTE FUNCTION interview_touch_updated_at();
CREATE TRIGGER interview_responsibles_touch BEFORE UPDATE ON interview_responsibles FOR EACH ROW EXECUTE FUNCTION interview_touch_updated_at();
CREATE TRIGGER interview_sessions_touch     BEFORE UPDATE ON interview_sessions     FOR EACH ROW EXECUTE FUNCTION interview_touch_updated_at();
CREATE TRIGGER interview_participants_touch BEFORE UPDATE ON interview_participants FOR EACH ROW EXECUTE FUNCTION interview_touch_updated_at();
