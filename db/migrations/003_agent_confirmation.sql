-- Підтвердження співбесіди голосовим агентом.
-- Reserved  — бронь від автоматизації (кандидат ще не підтвердив час);
-- Confirmed — кандидат підтвердив час агенту (або менеджер записав вручну);
-- Cancelled — бронь знято (відмова агенту, перезапис вручну тощо), причина — у cancel_reason.

ALTER TABLE interview_participants
  ADD COLUMN confirmed_at  timestamptz,
  ADD COLUMN cancel_reason text NOT NULL DEFAULT '';

-- Журнал запитів голосового агента (для перевірки інтеграції й розбору спірних випадків)
CREATE TABLE interview_agent_events (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keycrm_id   text    NOT NULL DEFAULT '',
  confirmed   boolean,
  status_id   integer,
  payload     jsonb   NOT NULL DEFAULT '{}',
  result      text    NOT NULL DEFAULT '',   -- confirmed | already_confirmed | cancelled | already_cancelled | no_booking | invalid | error
  details     jsonb   NOT NULL DEFAULT '{}', -- учасник, сесія, синхронізація KeyCRM, перенесені ліди
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX interview_agent_events_keycrm_idx ON interview_agent_events (keycrm_id, created_at DESC);
